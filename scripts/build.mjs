import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const { name } = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const check = process.argv.includes('--check');

async function compile(file, target, module) {
  const source = await readFile(join(root, file), 'utf8');
  const { outputText, diagnostics = [] } = ts.transpileModule(source, {
    fileName: file,
    compilerOptions: { target, module, newLine: ts.NewLineKind.LineFeed },
    reportDiagnostics: true,
  });
  if (diagnostics.length > 0) {
    throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
      getCanonicalFileName: n => n,
      getCurrentDirectory: () => root,
      getNewLine: () => '\n',
    }));
  }
  return outputText;
}

const host = await compile('src/host/index.ts', ts.ScriptTarget.ES2022, ts.ModuleKind.ESNext);
const client = await compile('src/client/index.ts', ts.ScriptTarget.ES2020, ts.ModuleKind.CommonJS);

// DSH serves the Client entry as a classic script and materializes its exports lazily.
const clientBundle = `/** Generated by scripts/build.mjs from src/client/index.ts. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(name)},
  factory(require) {
    const exports = {};
${client}    return exports;
  },
});
`;
const hostBundle = `/** Generated by scripts/build.mjs from src/host/index.ts. */\n${host}`;

for (const [file, content] of [['index.js', hostBundle], ['client.js', clientBundle]]) {
  const path = join(root, file);
  if (!check) {
    await writeFile(path, content);
    console.log(`wrote ${file} (${Buffer.byteLength(content)} bytes)`);
    continue;
  }
  const current = await readFile(path, 'utf8').catch((error) => {
    if (error.code !== 'ENOENT') throw error;
    return undefined;
  });
  if (current !== content) {
    console.error(`${file} is missing or stale. Run npm run build.`);
    process.exitCode = 1;
  } else {
    console.log(`${file} is up to date`);
  }
}
